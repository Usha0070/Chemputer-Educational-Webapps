// Keeps old links working. Reads `legacy:` from every src/content/sims/*.mdx and regenerates:
//   1. the 301 redirects in vercel.json (Vercel keeps the query string, e.g. ?z=24)
//   2. tiny redirect stubs at the repository root for GitHub Pages, which still serves `main` as-is
//      (meta refresh + JS that forwards the query string, plus a canonical link)
// Run: npm run legacy   (CI fails if the committed files are out of date)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SITE_URL = 'https://chemputer-educational-webapps.vercel.app';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const simsDir = path.join(root, 'src/content/sims');

/** [{ legacy: 'electron_configue_calculator.html', to: '/ssc/04-periodic-table/electron-configuration-calculator/' }] */
export function legacyMap() {
  return readdirSync(simsDir)
    .filter((f) => f.endsWith('.mdx'))
    .sort()
    .flatMap((f) => {
      const front = readFileSync(path.join(simsDir, f), 'utf8').split('---')[1] ?? '';
      const legacy = front.match(/^legacy:\s*['"]?([^'"\s]+)['"]?\s*$/m)?.[1];
      const chapter = front.match(/^chapter:\s*['"]?([^'"\s]+)['"]?\s*$/m)?.[1];
      return legacy && chapter ? [{ legacy, to: `/ssc/${chapter}/${f.replace(/\.mdx$/, '')}/` }] : [];
    });
}

export function stubHtml(to) {
  const url = SITE_URL + to;
  return `<!doctype html>
<!-- Redirect stub for the old GitHub Pages address. Generated by scripts/legacy.mjs; do not edit. -->
<html lang="bn">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Chemputer: নতুন ঠিকানায় যাচ্ছি…</title>
<link rel="canonical" href="${url}">
<meta name="robots" content="noindex">
<script>location.replace(${JSON.stringify(url)} + location.search + location.hash);</script>
<meta http-equiv="refresh" content="0; url=${url}">
</head>
<body style="margin:0;min-height:100vh;display:grid;place-items:center;background:#050101;color:#f6f6f6;font-family:system-ui,sans-serif">
<p>Chemputer নতুন ঠিকানায় চলে গেছে: <a style="color:#fcde56" href="${url}">${url}</a></p>
</body>
</html>
`;
}

function main() {
  const map = legacyMap();
  const vercelPath = path.join(root, 'vercel.json');
  const vercel = JSON.parse(readFileSync(vercelPath, 'utf8'));
  vercel.redirects = map.map(({ legacy, to }) => ({ source: `/${legacy}`, destination: to, statusCode: 301 }));
  writeFileSync(vercelPath, JSON.stringify(vercel, null, 2) + '\n');
  writeFileSync(path.join(root, 'index.html'), stubHtml('/'));
  for (const { legacy, to } of map) writeFileSync(path.join(root, legacy), stubHtml(to));
  console.log(`vercel.json: ${map.length} redirects; GitHub Pages stubs: index.html + ${map.length} pages.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
